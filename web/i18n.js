let currentLanguage = localStorage.getItem('kisan_lang') || 'en';

function setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) langCode = 'en';
    currentLanguage = langCode;
    localStorage.setItem('kisan_lang', langCode);

    // Keep clean standard LTR layout for all languages including Urdu to avoid layout distortion
    document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.classList.toggle('lang-ur', langCode === 'ur');

    applyTranslations();

    // Notify application to re-render all dynamic data in new language
    if (typeof window.onLanguageChanged === 'function') {
        window.onLanguageChanged(langCode);
    }
}

function t(key) {
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
}

function applyTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
            el.setAttribute('placeholder', t(key));
        } else {
            el.textContent = t(key);
        }
    });

    // Update active state in language selector
    const currentLangObj = LANGUAGES.find(l => l.code === currentLanguage) || LANGUAGES[0];
    const langBtnText = document.getElementById('currentLangLabel');
    if (langBtnText) {
        langBtnText.textContent = currentLangObj.native;
    }
}
